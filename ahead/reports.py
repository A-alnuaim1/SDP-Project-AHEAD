def _identity(r):
    """Who and what the report is about: only facts that were given, two to a row in a fixed order (record, doctor,
    source, review), so each keeps its place; a fact without a partner spans its row."""
    def pair(label, text, bold=False):
        return label, Paragraph(_esc(text, breaks=True), ST["id_b" if bold else "id"])

    if r.patient:
        facts = ([pair("Prepared for", r.name, True)] if r.name else []) + [pair("Screening type", "Self-screening")]
    else:
        # status=None is a session screening: no saved record, so its label names the screening, not an ID.
        record = pair("Patient ID", r.patient_id or "Not recorded", True) if r.review else pair(
            "Screening type", r.patient_id or "Session screening")
        facts = [record] + [
            pair(label, text) for label, text in (("Reviewing doctor", r.reviewer), ("Source", r.source)) if text]
        if r.review:   # Excluded is administrative: neutral ink, so it never reads as an alarm beside the result
            ink, word = {"reviewed": (CLEAR[1], "Reviewed"), "excluded": (TITLE, "Excluded")}.get(
                r.status, (WARNING_INK, "Pending review"))
            when = f" on {_esc(r.reviewed_at)}" if r.status == "reviewed" and r.reviewed_at else ""
            facts.append(("Review status", Paragraph(f'<font color="{_hex(ink)}"><b>{word}</b></font>{when}', ST["id"])))
    rows = [facts[i:i + 2] for i in range(0, len(facts), 2)]
    lw, half = 84, CONTENT_W / 2
    data, style = [], [("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                       ("RIGHTPADDING", (0, 0), (-1, -1), 10), ("LEFTPADDING", (2, 0), (2, -1), INSET),
                       ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                       ("TOPPADDING", (0, 0), (0, -1), 6.2), ("TOPPADDING", (2, 0), (2, -1), 6.2),
                       ("LINEABOVE", (0, 0), (-1, 0), 0.6, BORDER, 0), ("LINEBELOW", (0, 0), (-1, -1), 0.6, BORDER, 0)]
    for i, row in enumerate(rows):
        cells = [cell for label, value in row for cell in (Paragraph(label, ST["id_label"]), value)]
        data.append(cells + ["", ""] * (2 - len(row)))
        style.append(("LINEBEFORE", (2, i), (2, i), 0.6, BORDER, 0) if len(row) == 2 else ("SPAN", (1, i), (3, i)))
    table = Table(data, colWidths=[lw, half - lw, lw, half - lw])
    table.setStyle(TableStyle(style))
    return table


def _label_width(items, width, share):
    """`share` of a label-and-value pair for the label, narrowed (never below the widest label, within 55%) when an
    answer is long, so 'Current smoker - now smokes every day' takes two lines rather than three."""
    pad, pill = INSET + 8, _blank_pill().wrap(width, 20)[0]
    need_label = max((stringWidth(label, "Helvetica", 8.4) for label, _ in items), default=0) + pad
    need_value = max((stringWidth(value, "Helvetica-Bold", 8.4) if value else pill for _, value in items), default=0) + pad
    return min(width * share, max(width - need_value, min(need_label, width * 0.55), width * 0.38))


def _values_table(rows, width, pad=None):
    """Zebra-striped inputs. Full width, two pairs go to a row, so values sit near their labels and long lists
    stay short and split cleanly."""
    def cells(item):
        if item is None:
            return ["", ""]
        label, value = item
        shown = (_blank_pill() if value is None else Paragraph(value, ST["unrecorded"]) if value == NOT_RECORDED
                 else Paragraph(_esc(value), ST["value"]))   # Not recorded: the dataset's own answer, not a blank
        return [Paragraph(_esc(label), ST["label"]), shown]

    head = lambda: [_eyebrow("Input"), _eyebrow("Value")]
    if width <= LEFT_W:
        lw, halves, pad = _label_width(rows, width, 0.6), [(0, 1)], pad or 3.9
        widths, data = [lw, width - lw], [head()] + [cells(row) for row in rows]
    else:
        half, pad, halves = (width - 18) / 2, pad or 4.2, [(0, 1), (3, 4)]
        left, right = (_label_width(items, half, 0.58) for items in (rows[::2], rows[1::2]))
        widths = [left, half - left, 18, right, half - right]
        data = [head() + [""] + head()] + [cells(a) + [""] + cells(b) for a, b in zip_longest(rows[::2], rows[1::2])]
    style = [("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("LEFTPADDING", (0, 0), (-1, -1), INSET),
             ("RIGHTPADDING", (0, 0), (-1, -1), 8), ("TOPPADDING", (0, 0), (-1, -1), pad),
             ("BOTTOMPADDING", (0, 0), (-1, -1), pad), ("TOPPADDING", (0, 0), (-1, 0), 1),
             ("BOTTOMPADDING", (0, 0), (-1, 0), 5), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, ZEBRA])]
    for a, b in halves:
        style += [("LINEBELOW", (a, 0), (b, 0), 1.0, NAVY, 0), ("LINEBELOW", (a, -1), (b, -1), 0.6, BORDER, 0)]
    if len(halves) == 2:
        style.append(("BACKGROUND", (2, 0), (2, -1), WHITE))
    table = Table(data, colWidths=widths, repeatRows=1)
    table.setStyle(TableStyle(style))
    return table


