class _NumberedCanvas(Canvas):
    """Holds every page until the end so the footer can say 'Page x of y'."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.pages = []

    def showPage(self):
        self.pages.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        for state in self.pages:
            self.__dict__.update(state)
            self.setStrokeColor(BORDER)
            self.setLineWidth(0.6)
            self.line(MARGIN, FOOTER_Y + 11, PAGE_W - MARGIN, FOOTER_Y + 11)
            self.setFillColor(MUTED)
            self.setFont("Helvetica", 7.2)
            self.drawString(MARGIN, FOOTER_Y, FOOTER)
            self.setFont("Helvetica-Bold", 7.2)
            self.drawRightString(PAGE_W - MARGIN, FOOTER_Y, f"Page {self._pageNumber} of {len(self.pages)}")
            super().showPage()
        super().save()


class _Doc(BaseDocTemplate):
    """Records how far down each page the content reached (0..1 of the frame height)."""

    def afterPage(self):
        f = self.frame
        self.fills = getattr(self, "fills", []) + [(f._y2 - f._y) / (f._y2 - f._y1)]


def _build(r, layout, brk=None):
    stream = BytesIO()
    doc = _Doc(stream, pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN, topMargin=0, bottomMargin=BOTTOM,
               title=_title(r), author="AHEAD", subject="Educational screening estimate", creator="AHEAD")
    frame = lambda top, name: Frame(MARGIN, BOTTOM, CONTENT_W, top - BOTTOM, id=name, leftPadding=0, rightPadding=0,
                                    topPadding=0, bottomPadding=0)
    doc.addPageTemplates([PageTemplate("First", [frame(FIRST_TOP, "first")], onPage=_first_band(r),
                                       autoNextPageTemplate="Later"),
                          PageTemplate("Later", [frame(LATER_TOP, "later")], onPage=_later_band(r))])
    story, sections = _story(r, layout, brk)
    try:
        doc.build(story, canvasmaker=_NumberedCanvas)
    except LayoutError:   # a side-by-side row taller than a page: this layout can't hold the report
        return None
    return SimpleNamespace(pdf=stream.getvalue(), fills=doc.fills, pages=len(doc.fills), sections=sections)


def _render(r):
    """One A4 page whenever the content fits. Otherwise the fewest pages with the fullest first page whose last page
    is not SPARSE: the natural flow first, and whole sections moved over (latest first, so the reading notes stay
    with the result) only when every natural flow ends on a near-empty page."""
    side = 0 < len(r.values) <= 16   # a side-by-side row can't split across pages, so long lists stack
    flows, last = [], None
    # Later plans trim the section gaps, and the last one the rail's table rows, before a second page is allowed.
    plans = [(layout, gap, 2.6) for gap in (GAP, 9) for layout in (["side"] if side else []) + ["stacked", "rail"]]
    tightest = [("rail", 7, 2.0), ("rail", 6, 1.6)]
    # A Next step band can take the room a long input list needs, so its smaller forms are the last tries for one
    # page, on the tightest plan: tight, then for urgent the reasons' short lines, then (two or more of them) their
    # values on one line. Full words on tight spacing come before smaller words on roomier spacing.
    lines = sum(reason.line is not None for reason in r.track.reasons) if _urgent(r) else 0
    bands = (["tight"] + (["lines"] if _urgent(r) else []) + (["chips"] if lines > 1 else [])) if r.track else []
    for layout, gap, rows, band in [(*plan, "full") for plan in plans + tightest] + [
            (*tightest[-1], band) for band in bands]:
        r.gap, r.rows, r.band = gap, rows, band
        out = _build(r, layout)
        if out and out.pages == 1:
            if out.fills[0] < 0.86:   # share spare height between the section gaps; line spacing never changes
                r.gap = GAP + min(9.0, (0.9 - out.fills[0]) * (FIRST_TOP - BOTTOM) / out.sections)
                roomy, r.gap = _build(r, layout), GAP
                out = roomy if roomy and roomy.pages == 1 else out
            return out.pdf
        if out and layout != "rail":   # the rail's one tall row would leave a hole on page 1
            flows.append((layout, gap, out))
        last = out or last
    r.band = "full"   # the flows below were built with the full band (the smaller ones only try the tightest plan)
    if all(out.fills[-1] < SPARSE for *_, out in flows):
        for layout, gap, out in list(flows):
            r.gap = gap
            for brk in range(out.sections - 1, 0, -1):   # latest break first: the fullest first page
                moved = _build(r, layout, brk)
                if moved and moved.pages == out.pages and moved.fills[-1] >= SPARSE:
                    flows.append((layout, gap, moved))
                    break
    if not flows and not last:
        raise ValueError("The report content does not fit the page layout.")
    return min([out for *_, out in flows] or [last], key=lambda o: (o.pages, o.fills[-1] < SPARSE, -o.fills[0])).pdf
