def _tracked_width(text, size, space):
    return stringWidth(text, "Helvetica-Bold", size) + space * max(len(text) - 1, 0)


def _tracked(c, x, y, text, size, space, color, align="left"):
    """Letter-spaced bold caps; returns the drawn width."""
    width = _tracked_width(text, size, space)
    x -= width if align == "right" else 0
    c.saveState()   # char spacing is graphics state: keep it from leaking into later text
    t = c.beginText(x, y)
    t.setFont("Helvetica-Bold", size)
    t.setCharSpace(space)
    t.setFillColor(color)
    t.textOut(text)
    c.drawText(t)
    c.restoreState()
    return width


def _fit(text, font, size, width):
    if stringWidth(text, font, size) <= width:
        return text
    while text and stringWidth(text + "…", font, size) > width:
        text = text[:-1]
    return text.rstrip() + "…"


def _logo(c, x, y, size):
    """The AHEAD mark from assets/logo.svg (64x64 viewBox), drawn with canvas paths."""
    c.saveState()
    c.translate(x, y)
    c.scale(size / 64, size / 64)
    c.setFillColor(NAVY_2)
    c.roundRect(0, 0, 64, 64, 16, stroke=0, fill=1)
    c.setLineCap(1)
    c.setLineJoin(1)
    for color, width, points in ((WHITE, 5, [(14, 12), (32, 52), (50, 12)]),
                                 (CYAN, 4, [(19, 24), (25, 24), (28.5, 32), (33, 18), (36.5, 26), (45, 26)])):
        c.setStrokeColor(color)
        c.setLineWidth(width)
        path = c.beginPath()
        path.moveTo(*points[0])
        for point in points[1:]:
            path.lineTo(*point)
        c.drawPath(path, stroke=1, fill=0)
    c.restoreState()


def _track_icon(c, x, y, size, track, color):
    """The web panel's icon for a track (assets/icons/dashboard: flag, gauge, clipboard check, 24x24 viewBox) in
    white on a tone tile, drawn with canvas paths."""
    c.saveState()
    c.setFillColor(color)
    c.roundRect(x, y, size, size, size * 0.3, stroke=0, fill=1)
    c.translate(x + size * 0.225, y + size * 0.775)   # the icon fills the middle 55%, SVG's y axis pointing down
    c.scale(size * 0.55 / 24, -size * 0.55 / 24)
    c.setStrokeColor(WHITE)
    c.setLineWidth(2)
    c.setLineCap(1)
    c.setLineJoin(1)
    p = c.beginPath()
    if track == "urgent":
        p.moveTo(4, 15)
        for curve in ((4, 15, 5, 14, 8, 14), (11, 14, 13, 16, 16, 16), (19, 16, 20, 15, 20, 15)):
            p.curveTo(*curve)
        p.lineTo(20, 3)
        for curve in ((20, 3, 19, 4, 16, 4), (13, 4, 11, 2, 8, 2), (5, 2, 4, 3, 4, 3)):
            p.curveTo(*curve)
        p.close()
        p.moveTo(4, 22)
        p.lineTo(4, 15)
    elif track == "at_risk":
        p.arc(2, 4, 22, 24, 150, 240)
        p.moveTo(12, 14)
        p.lineTo(16, 10)
    else:
        p.moveTo(9, 5)   # the board: open at the top for the clip, with rounded corners
        for x0, y0, start, end in ((5, 5, 270, (5, 19)), (5, 17, 180, (17, 21)), (15, 17, 90, (19, 7)),
                                   (15, 5, 0, (15, 5))):
            p.arcTo(x0, y0, x0 + 4, y0 + 4, start, -90)
            p.lineTo(*end)
        p.roundRect(9, 3, 6, 4, 2)
        p.moveTo(9, 14)
        p.lineTo(11, 16)
        p.lineTo(15, 12)
    c.drawPath(p, stroke=1, fill=0)
    c.restoreState()


class Drawn(Flowable):
    """A fixed-height flowable painted by paint(canvas, width)."""

    def __init__(self, height, paint, width=None):
        super().__init__()
        self.height, self.paint, self.fixed = height, paint, width

    def wrap(self, aw, ah):
        self.width = min(aw, self.fixed or aw)
        return self.width, self.height

    def draw(self):
        self.paint(self.canv, self.width)


def _heading(text):
    def paint(c, w):
        c.setFillColor(NAVY)
        c.setFont("Helvetica-Bold", 10.2)
        c.drawString(0, 6.2, text)
        c.setFillColor(TEAL)
        c.rect(0, 0, 20, 1.8, stroke=0, fill=1)
    return Drawn(16.8, paint)


def _eyebrow(text):
    return Drawn(8.3, lambda c, w: _tracked(c, 0, 1.5, text.upper(), 6.8, 0.9, MUTED))


def _blank_pill(text="Not provided"):
    """An empty answer in a dashed outline: clearly empty, still readable."""
    def paint(c, w):
        c.setStrokeColor(DASH)
        c.setLineWidth(0.7)
        c.setDash(1.6, 1.3)
        c.roundRect(0.35, 0.35, w - 0.7, 11.7, 5.85, stroke=1, fill=0)
        c.setDash()
        c.setFillColor(MUTED)
        c.setFont("Helvetica-Oblique", 7.8)
        c.drawString(6.3, 3.4, text)
    return Drawn(12.4, paint, stringWidth(text, "Helvetica-Oblique", 7.8) + 13)


def _metric_bar(label, frac):
    def paint(c, w):
        c.setFillColor(TITLE)
        c.setFont("Helvetica-Bold", 8.4)
        c.drawString(0, 8, label)
        c.setFont("Helvetica-Bold", 9.6)
        c.drawRightString(w, 8, "Not available" if frac is None else _pct(frac))
        c.setFillColor(BORDER)
        c.rect(0, 0, w, 4, stroke=0, fill=1)
        if frac:
            c.setFillColor(TEAL)
            c.rect(0, 0, max(2, w * frac), 4, stroke=0, fill=1)
    return Drawn(17, paint)


class Bullet(Flowable):
    """List item whose marker hangs in the margin, so the text lines up with the heading above it."""

    def __init__(self, text, box):
        super().__init__()
        self.para, self.box = Paragraph(text, ST["item"]), box

    def wrap(self, aw, ah):
        self.width, self.height = aw, self.para.wrap(aw, ah)[1]
        return aw, self.height

    def draw(self):
        c, s = self.canv, self.para.style
        self.para.drawOn(c, 0, 0)
        cy = self.height - s.leading + (s.leading - s.fontSize) / 2 + 4.1   # optical centre of the first line
        if self.box:
            c.setStrokeColor(TEAL_STRONG)
            c.setLineWidth(0.9)
            c.roundRect(-14, cy - 3.6, 7.2, 7.2, 1.4, stroke=1, fill=0)
        else:
            c.setFillColor(TEAL)
            c.circle(-10.5, cy, 2.3, stroke=0, fill=1)


class Box(Flowable):
    """Tinted container with an accent bar drawn inside it. Splits between (or inside) its paragraphs across pages;
    `target` stretches it to a shared height so neighbouring columns end level."""

    def __init__(self, content, bg=SOFT, accent=TEAL, pad=(9, 10), gap=0):
        super().__init__()
        self.content, self.bg, self.accent, self.pad, self.gap, self.target = content, bg, accent, pad, gap, None

    def _copy(self, content):
        return Box(content, self.bg, self.accent, self.pad, self.gap)

    def wrap(self, aw, ah):
        self.width, gaps = aw, len(self.content) - 1
        self.sizes = [f.wrap(aw - 2 * INSET, 10_000)[1] for f in self.content]
        natural = sum(self.pad) + sum(self.sizes) + self.gap * gaps
        extra = max(0.0, (self.target or 0) - natural)
        self.gap_extra = min(extra / (gaps + 2), 4) if gaps else 0
        self.top_extra = min((extra - self.gap_extra * gaps) / 2, 5)   # text stays near the top
        self.height = natural + extra
        return aw, self.height

    def split(self, aw, ah):
        if self.wrap(aw, ah)[1] <= ah:
            return [self]
        inner, room = aw - 2 * INSET, ah - sum(self.pad)
        first, rest, used = [], list(self.content), 0
        while rest:
            h = rest[0].wrap(inner, 10_000)[1]
            if used + h <= room:
                first.append(rest.pop(0))
                used += h + self.gap
                continue
            parts = rest[0].split(inner, room - used) if room - used > 24 else []
            if len(parts) > 1:
                first.append(parts[0])
                rest[0:1] = parts[1:]
            break
        return [self._copy(first), self._copy(rest)] if first and rest else []

    def draw(self):
        c = self.canv
