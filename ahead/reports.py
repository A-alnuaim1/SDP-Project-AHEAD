def _blank(value):
    if value is None:
        return True
    if isinstance(value, str):
        return not value.strip()
    try:
        return bool(value != value)   # NaN, numpy or pandas missing values
    except (TypeError, ValueError):   # pd.NA refuses to be truth-tested
        return True


def _text(value):
    return "" if _blank(value) else _printable(str(value).strip())


def _short(value, limit=200):
    """Identity fields, factors and values sit in table cells that can't split across pages, so runaway text is cut."""
    text = " ".join(_text(value).split())
    return text if len(text) <= limit else text[:limit - 1].rstrip() + "…"


def _fits(text):
    """Whether the built-in PDF fonts can draw it: Helvetica's Western set, or the Symbol and Dingbats fonts that
    ReportLab swaps in for characters such as ≥ and ✓. Anything else prints as a black box."""
    for encoding in ("WinAnsiEncoding", "SymbolEncoding", "ZapfDingbatsEncoding"):
        try:
            text.encode(encoding)
            return True
        except UnicodeEncodeError:
            pass
    return text in "\n\t"


def _printable(text):
    """Text the PDF can draw. Accents outside the font are dropped (ş -> s), dashes and spaces become plain ones,
    emoji and other symbols are removed, and a run of another script (Arabic, say) becomes one marker, never boxes.
    Arabic proper needs an embedded Unicode font with text shaping."""
    if _fits(text):
        return text
    out = []
    for ch in text.translate(LOOKALIKES):
        if not _fits(ch):
            kind = unicodedata.category(ch)
            base = str(unicodedata.decimal(ch, "")) or "".join(
                c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
            ch = (base if base and all(map(_fits, base)) else " " if kind == "Zs" else "-" if kind == "Pd"
                  else "\x00" if kind[0] in "LN" else "\x01")
        out.append(ch)
    text = re.sub(r"[ \t]*\x01+", "", "".join(out))   # a dropped emoji takes its leading space with it
    return re.sub(r"\x00(?:[\x00\W]*\x00)?", OTHER_SCRIPT, text)   # 'د. سارة' is one run, not two markers


def _esc(value, breaks=False):
    """User text for a Paragraph: markup escaped, control characters dropped, line breaks kept. breaks: an ID or file
    name too long for an identity cell may wrap after - _ / or , (at a hair-thin space) rather than mid-token."""
    text = escape("".join(ch for ch in str(value) if ch in "\n\t" or ord(ch) >= 32))
    if breaks:
        text = re.sub(r"\S{24,}", lambda m: re.sub(r"(?<=[-_/,])(?=\w)", '<font size="0.1"> </font>', m.group())
                      if stringWidth(m.group(), "Helvetica-Bold", 9) > 160 else m.group(), text)
    return text.replace("\n", "<br/>").replace(OTHER_SCRIPT, f'<font color="{_hex(MUTED)}"><i>{OTHER_SCRIPT}</i></font>')


def _pct(x, digits=1):
    return f"{x * 100:.{digits}f}%"


def _clamp(x):
    return max(0.0, min(1.0, float(x)))


def _metric(metrics, key):
    return None if _blank(metrics.get(key)) else _clamp(metrics[key])


def _hex(color):
    return "#" + color.hexval()[2:]


def _stats(disease):
    try:
        return feature_summary(disease)
    except Exception:   # the PDF still renders, with plainer values, if the reference data can't load
        return {}


def _sentence(label):
    """'History of Hypertension' -> 'History of hypertension'; acronyms and units such as HbA1c and mmHg stay."""
    return re.sub(r"(?<=[ -])[A-Z][a-z]+\b", lambda m: m.group().lower(), label)


def _shown(feature, value, info, rule=None):
    """An entered value as the patient form shows it, NOT_RECORDED for the dataset's own "No Info" answer, or None
    when it was left blank. A value an urgent rule reads (rule, from ahead/triage.py) keeps the Next step band's two
    decimals, so the table never rounds it onto or across its cut-off (eGFR 59.96 is not 60)."""
    if _blank(value) or (info.get("kind") != "category" and str(value).strip().lower() in BLANK_MARKERS):
        return None
    if isinstance(value, bool) or type(value).__name__ == "bool_":
        return "Yes" if value else "No"
    try:
        number = float(value)
    except (TypeError, ValueError):
        number = None
    if info.get("kind") == "category" or number is None or not math.isfinite(number):
        text = _short(value, 120)
        if text.lower() == "no info":
            return NOT_RECORDED
        known = text.lower() in {str(option).lower() for option in info.get("options", ())}
        return text[:1].upper() + text[1:].lower() if known else text
    if info.get("binary") and number in (0, 1):
        return (("Male", "Female") if feature in GENDER_CODED_FIELDS else ("No", "Yes"))[int(number)]
    if number.is_integer():
        return str(int(number))
    if rule is not None:   # in full when two decimals would still cross the cut-off (59.996), as the band prints it
        text = number_text(number)
        return text if rule.trips(float(text)) == rule.trips(number) else repr(number)
    # BMI 31.2, HbA1c 6.4, creatinine 1.23, and two significant figures for a tiny value (0.0049) so it isn't "0".
    places = 1 if abs(number) >= 10 else 2 if abs(number) >= 0.01 else min(6, 1 - math.floor(math.log10(abs(number))))
    return f"{round(number, places) + 0.0:.{places}f}".rstrip("0").rstrip(".")   # + 0.0 turns -0.0 into 0.0


def _track(track, disease, flagged, audience):
    """The band's words from a triage() result, or None for no band. A track sorted for another result would
    contradict the panel above it (Not flagged over an At risk band), so it is refused rather than printed."""
    if track is None:
        return None
    if not isinstance(track, dict) or track.get("track") not in TRACKS:
        raise ValueError("track must be the result of ahead.triage.triage() for this screening.")
    if track.get("disease") != disease or track.get("flagged") != flagged:
        raise ValueError("track was sorted for a different result: pass triage() with this report's score and "
                         "threshold.")
    text, reasons = track_text(track, audience), track.get("reasons") or ()
    return SimpleNamespace(name=track["track"], label=_text(text["label"]), summary=_text(text["summary"]),
                           reasons=[SimpleNamespace(words=_text(reason[audience]), line=_reason_line(reason))
                                    for reason in reasons],
                           values=sum(reason.get("kind") != ADULTS_ONLY for reason in reasons))


def _reason_line(reason):
    """(label, value, cut-off) for the band's short forms, or None for a reason that keeps its words there: blood
    pressure (the patient's emergency-care line) and age (why a flagged child needs a doctor)."""
    if reason.get("kind") in ("blood_pressure", ADULTS_ONLY):
        return None
    parts = tuple(_text(reason.get(key)) for key in ("label", "value_text", "cut_off_text"))
    return parts if all(parts) else None


def _model_name(model):
    name = _text(model)
    if name in MODEL_NAMES:
        return MODEL_NAMES[name]
    words = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name.replace("_", " ")).split()
    text = " ".join(w if w.isupper() else w.lower() for w in words)
    return text[:1].upper() + text[1:] or "Screening"


def _when(value):
    """A datetime (naive means UTC, like stored timestamps) or ISO text as Dubai time; other text as given."""
    if _blank(value):
        return ""
    if isinstance(value, str):
        try:
            value = datetime.fromisoformat(value.strip())
        except ValueError:
            return _short(value, 40)
    if not isinstance(value, datetime):
        return str(value)
    local = (value if value.tzinfo else value.replace(tzinfo=timezone.utc)).astimezone(DUBAI)
    return f"{local.day} {local:%b %Y, %H:%M}"


